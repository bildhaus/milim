use std::fs;
use std::path::{Path, PathBuf};

use milim_control_contract::*;
use serde_json::json;
use ts_rs::TS;

fn main() {
    let check = std::env::args().any(|arg| arg == "--check");
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("workspace root");
    let contract = generated_contract();
    let fixture = generated_fixture();
    let targets = [
        (
            root.join("apps/desktop/src/generated/control-v1.ts"),
            contract.as_str(),
        ),
        (
            root.join("apps/mobile/src/control/generated-v1.ts"),
            contract.as_str(),
        ),
        (
            root.join("crates/milim-control-contract/fixtures/control-v1.json"),
            fixture.as_str(),
        ),
    ];
    let mut stale = Vec::new();
    for (target, output) in targets {
        if check {
            if fs::read_to_string(&target).ok().as_deref() != Some(output) {
                stale.push(target);
            }
        } else {
            write(&target, output);
        }
    }
    if !stale.is_empty() {
        eprintln!("generated control contract is stale:");
        for target in stale {
            eprintln!("  {}", target.display());
        }
        std::process::exit(1);
    }
}

