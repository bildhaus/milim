fn generated_contract() -> String {
    let mut output = String::from(
        "// @generated by milim-control-contract. Do not edit by hand.\n\n\
         export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n\n",
    );
    macro_rules! decls {
        ($($ty:ty),+ $(,)?) => {$({
            let declaration = <$ty as TS>::decl()
                .replacen("type ", "export type ", 1)
                .replace("bigint", "number");
            output.push_str(&declaration);
            output.push_str("\n\n");
        })+};
    }
    decls!(
        ControlProtocolRangeV1,
        ControlCapabilitiesV1,
        ThreadLinkV1,
        FrozenLinkedThreadGrantV1,
        MailboxOriginV1,
        ThreadOriginV1,
        ThreadSummaryV1,
        AgentSummaryV1,
        AgentSnapshotV1,
        ControlAttachmentV1,
        GenerationSettingsV1,
        FrozenRunConfigV1,
        RunCapabilitiesV1,
        RunSnapshotV1,
        PendingApprovalV1,
        QueuedTurnV1,
        PendingInputV1,
        AppearanceColorsV1,
        AppearanceGlassV1,
        AppearanceBackgroundV1,
        AppearanceBordersV1,
        AppearanceTypographyV1,
        AppearanceSnapshotV1,
        ControlBootstrapV1,
        TimelineItemV1,
        TimelinePageV1,
        ControlEventV1,
        ControlCommandStatusV1,
        ControlCommandKindV1,
        ControlCommandV1,
        ControlCommandResultV1,
        ResolvedRunCompositionV1,
        EffectiveRunPreviewRequestV1,
        EffectiveRunPreviewV1,
        RunEventV1,
        RunEventPageV1,
        RunInspectionV1,
    );
    output.truncate(output.trim_end().len());
    output.push('\n');
    output
}

fn write(path: &Path, output: &str) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("create generated contract directory");
    }
    fs::write(path, output).expect("write generated contract");
}
