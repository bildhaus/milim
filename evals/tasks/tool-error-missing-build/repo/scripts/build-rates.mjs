// Generate src/generated/rates.js from the reference rate CSV.
//
//   node scripts/build-rates.mjs --input data/rates.csv --out src/generated/rates.js

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { parseArgs } from "node:util";

const { values } = parseArgs({ options: { input: { type: "string" }, out: { type: "string" } } });
if (!values.input || !values.out) {
  console.error("usage: node scripts/build-rates.mjs --input <rates.csv> --out <rates.js>");
  process.exit(2);
}

const [header, ...rows] = readFileSync(values.input, "utf8").trim().split("\n");
if (header.trim() !== "code,name,rate_per_usd,minor_units") {
  console.error(`unexpected header in ${values.input}: ${header}`);
  process.exit(1);
}

const rates = {};
for (const row of rows) {
  const [code, name, ratePerUsd, minorUnits] = row.trim().split(",");
  rates[code] = {
    name,
    ratePerUsd: Number(ratePerUsd),
    // Most currencies have two decimal places.
    minorUnits: Number(minorUnits) || 2,
  };
}

mkdirSync(dirname(values.out), { recursive: true });
writeFileSync(
  values.out,
  `// Generated by scripts/build-rates.mjs from ${values.input}. Do not edit.\nexport const RATES = ${JSON.stringify(rates, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(rates).length} currencies to ${values.out}`);
