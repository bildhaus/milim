// Generate src/generated/<name>.js validators from schema/<name>.json.
//   node scripts/generate.mjs        (also: npm run generate)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";

const TYPES = { string: "string", integer: "number", boolean: "boolean" };

function render(name, schema) {
  const title = name[0].toUpperCase() + name.slice(1);
  const checks = schema.fields.map((field) => {
    const type = TYPES[field.type];
    if (!type) throw new Error(`${name}.${field.name}: unsupported type ${field.type}`);
    const typeCheck =
      field.type === "integer"
        ? `!Number.isInteger(value.${field.name})`
        : `typeof value.${field.name} !== "${type}"`;
    const missing = `value.${field.name} === undefined`;
    return field.optional
      ? `  if (!(${missing}) && ${typeCheck}) errors.push("${field.name} must be ${field.type === "integer" ? "an integer" : `a ${type}`}");`
      : `  if (${missing}) errors.push("${field.name} is required");\n  else if (${typeCheck}) errors.push("${field.name} must be ${field.type === "integer" ? "an integer" : `a ${type}`}");`;
  });
  return `// Generated by scripts/generate.mjs from schema/${name}.json. Do not edit;
// change the schema and run \`npm run generate\` instead.

export const ${name}Fields = ${JSON.stringify(schema.fields.map((field) => field.name))};

/** Validation errors for a ${name} object (empty when it is valid). */
export function validate${title}(value) {
  const errors = [];
${checks.join("\n")}
  for (const key of Object.keys(value)) {
    if (!${name}Fields.includes(key)) errors.push(\`unknown field \${key}\`);
  }
  return errors;
}
`;
}

mkdirSync("src/generated", { recursive: true });
for (const file of readdirSync("schema").filter((entry) => entry.endsWith(".json")).sort()) {
  const name = file.replace(/\.json$/, "");
  writeFileSync(`src/generated/${name}.js`, render(name, JSON.parse(readFileSync(`schema/${file}`, "utf8"))));
}
