import { readFileSync, writeFileSync } from "node:fs";

const routes = JSON.parse(readFileSync(new URL("../routes.json", import.meta.url), "utf8"));
const pascal = (name) => name.replace(/(^|-)(\w)/g, (_, __, ch) => ch.toUpperCase());
const imports = routes
  .map((route) => `import { handle${pascal(route.handler)} } from "./handlers/${route.handler}.js";`)
  .join("\n");
const table = routes
  .map((route) => `  { method: "${route.method}", path: "${route.path}", handler: handle${pascal(route.handler)} },`)
  .join("\n");
writeFileSync(
  new URL("../src/routes.generated.js", import.meta.url),
  `// Generated by scripts/gen-routes.mjs from routes.json. Do not edit.\n${imports}\n\nexport const ROUTES = [\n${table}\n];\n`,
);
